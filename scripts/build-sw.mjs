// Generates sw.js with a precache list of every core file and a content-hash
// version, so each deploy updates cleanly and nothing is ever stale offline.
//   node scripts/build-sw.mjs
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, relative, sep } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
// Heavy, optional packs are cached on first use / from More ▸ Use offline.
const SKIP = [/^scripts\//, /^vendor\/tesseract\//, /^vendor\/mediapipe\//, /^vendor\/LICENSES\//,
  /^vendor\/pdfjs\/cmaps\//, /LICENSE[^/]*$/,   // CJK cmaps: cached on first use
  /(^|\/)\./, /\.md$/, /^sw\.js$/, /^CONTRACT/, /^README/, /^node_modules\//, /\.map$/];
// Hosts the worker refuses (as a network error) instead of letting the request out.
// Subdomains match too. MediaPipe's usage logger posts to odml.pa.googleapis.com and has
// no off switch; js/lib.js refuses it on the page and this catches any other path.
const BLOCK_HOSTS = ['odml.pa.googleapis.com'];

const files = [];
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    const rel = relative(ROOT, p).split(sep).join('/');
    if (SKIP.some(re => re.test(rel))) continue;
    statSync(p).isDirectory() ? walk(p) : files.push(rel);
  }
})(ROOT);
files.sort();

const hash = createHash('sha256');
for (const f of files) hash.update(f).update(readFileSync(join(ROOT, f)));
const VERSION = hash.digest('hex').slice(0, 10);
const PRECACHE = ['./', ...files.map(f => './' + f)];

const sw = `// AUTO-GENERATED by scripts/build-sw.mjs — do not edit by hand.
const VERSION = '${VERSION}';
const CORE = 'snappto-core-' + VERSION;
const PACKS = 'snappto-packs-v1';           // OCR + vision models (big, rarely change); js/app.js writes here too
const PRECACHE = ${JSON.stringify(PRECACHE, null, 0)};
const BLOCK = ${JSON.stringify(BLOCK_HOSTS)};

// A new version installs next to the old one and waits, so open pages keep the files
// they started with. The page tells it to take over ('skipWaiting') when the user taps
// Update in the top bar or on a cold start, then reloads: a page never mixes two versions.
self.addEventListener('install', e => {
  // cache: 'reload' skips the HTTP cache, so a new version never stores the old files.
  e.waitUntil(caches.open(CORE).then(c => c.addAll(PRECACHE.map(u => new Request(u, { cache: 'reload' })))));
});

self.addEventListener('message', e => {
  if (e.data !== 'skipWaiting') return;
  e.waitUntil((async () => {
    // Taking over deletes the old cache, so wait while another SnappTo tab still runs on it.
    const others = (await self.clients.matchAll({ type: 'window', includeUncontrolled: true }))
      .filter(c => c.id !== e.source?.id && c.url.startsWith(self.registration.scope));
    if (others.length) e.source?.postMessage('other-tabs-open');
    else await self.skipWaiting();
  })());
});

self.addEventListener('activate', e => {
  e.waitUntil((async () => {
    for (const k of await caches.keys()) if (k.startsWith('snappto-core-') && k !== CORE) await caches.delete(k);
    await self.clients.claim();
    for (const c of await self.clients.matchAll()) c.postMessage('precached');
  })());
});

const fromCache = async req => (await (await caches.open(CORE)).match(req, { ignoreSearch: true }))
  || (await (await caches.open(PACKS)).match(req, { ignoreSearch: true }));

self.addEventListener('fetch', e => {
  const req = e.request;
  const url = new URL(req.url);
  if (BLOCK.some(h => url.hostname === h || url.hostname.endsWith('.' + h))) {
    e.respondWith(Response.error());
    return;
  }
  if (req.method !== 'GET') return;
  if (url.origin !== self.location.origin) return;          // e.g. currency API → network only

  // Page loads: serve the cached app shell so it opens with no network.
  if (req.mode === 'navigate') {
    e.respondWith(caches.open(CORE).then(c => c.match('./index.html')).then(r => r || fetch(req)));
    return;
  }
  const isPack = /\\/vendor\\/(tesseract|mediapipe|pdfjs\\/cmaps)\\//.test(url.pathname);
  // More ▸ Use offline asks for a fresh copy and stores it itself: let it through.
  if (isPack && req.cache === 'reload') return;
  e.respondWith((async () => {
    const hit = await fromCache(req);
    if (hit) return hit;
    const res = await fetch(req);
    if (res.ok && res.type === 'basic') {
      const copy = res.clone();
      // waitUntil keeps the worker alive until the copy is written (iOS stops idle workers early).
      e.waitUntil(caches.open(isPack ? PACKS : CORE).then(c => c.put(req, copy)));
    }
    return res;
  })());
});
`;
writeFileSync(join(ROOT, 'sw.js'), sw);
const bytes = files.reduce((n, f) => n + statSync(join(ROOT, f)).size, 0);
console.log(`sw.js  version ${VERSION}  ·  ${PRECACHE.length} files precached  ·  ${(bytes / 1024 / 1024).toFixed(2)} MB core`);
